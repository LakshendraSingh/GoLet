package main

import (
	"fmt"
	"strings"
)

// ── Symbol table ──────────────────────────────────────────────────────────────

type Symbol struct {
	Name string
	Type GoType
}

type Scope struct {
	vars   map[string]*Symbol
	parent *Scope
}

func newScope(parent *Scope) *Scope {
	return &Scope{vars: make(map[string]*Symbol), parent: parent}
}

func (s *Scope) define(name string, t GoType) {
	s.vars[name] = &Symbol{Name: name, Type: t}
}

func (s *Scope) lookup(name string) *Symbol {
	if sym, ok := s.vars[name]; ok {
		return sym
	}
	if s.parent != nil {
		return s.parent.lookup(name)
	}
	return nil
}

// ── Codegen ───────────────────────────────────────────────────────────────────

type Codegen struct {
	sb      strings.Builder
	indent  int
	scope   *Scope
	funcs   map[string]*FuncDecl
	tmpCnt  int
}

func NewCodegen() *Codegen {
	return &Codegen{
		funcs: make(map[string]*FuncDecl),
		scope: newScope(nil),
	}
}

func (g *Codegen) w(format string, a ...interface{}) {
	fmt.Fprintf(&g.sb, "%*s", g.indent*2, "")
	fmt.Fprintf(&g.sb, format, a...)
	g.sb.WriteString("\n")
}

func (g *Codegen) raw(format string, a ...interface{}) {
	fmt.Fprintf(&g.sb, format, a...)
}

func (g *Codegen) push() { g.indent++ }
func (g *Codegen) pop()  { g.indent-- }

func (g *Codegen) tmpVar() string {
	g.tmpCnt++
	return fmt.Sprintf("_tmp%d", g.tmpCnt)
}

// ── Program ───────────────────────────────────────────────────────────────────

func (g *Codegen) Generate(prog *Program) (string, error) {
	// Collect function signatures first (for forward declarations)
	for _, fn := range prog.Funcs {
		g.funcs[fn.Name] = fn
	}

	// C preamble
	g.w("/* Generated by goc — mini Go compiler */")
	g.w("#include <stdio.h>")
	g.w("#include <stdlib.h>")
	g.w("#include <string.h>")
	g.w("#include <stdint.h>")
	g.w("")

	// Runtime helpers
	g.w("/* ── runtime helpers ── */")
	g.w("static const char* _bool_str(int b) { return b ? \"true\" : \"false\"; }")
	g.w("static void _print_int(long long v)    { printf(\"%%lld\", v); }")
	g.w("static void _print_str(const char* s)  { printf(\"%%s\", s); }")
	g.w("static void _print_bool(int b)         { printf(\"%%s\", _bool_str(b)); }")
	g.w("static void _println_int(long long v)  { printf(\"%%lld\\n\", v); }")
	g.w("static void _println_str(const char* s){ printf(\"%%s\\n\", s); }")
	g.w("static void _println_bool(int b)       { printf(\"%%s\\n\", _bool_str(b)); }")
	g.w("")

	// Forward declarations
	g.w("/* ── forward declarations ── */")
	for _, fn := range prog.Funcs {
		if err := g.genFuncDecl(fn, true); err != nil {
			return "", err
		}
	}
	g.w("")

	// Function bodies
	for _, fn := range prog.Funcs {
		if err := g.genFuncDecl(fn, false); err != nil {
			return "", err
		}
		g.w("")
	}

	return g.sb.String(), nil
}

// ── Functions ─────────────────────────────────────────────────────────────────

func (g *Codegen) genFuncDecl(fn *FuncDecl, forwardOnly bool) error {
	// Build signature
	retC := fn.ReturnType.CName()
	var params []string
	for _, p := range fn.Params {
		params = append(params, fmt.Sprintf("%s %s", p.Type.CName(), p.Name))
	}
	paramStr := strings.Join(params, ", ")
	if paramStr == "" {
		paramStr = "void"
	}

	cName := fn.Name
	if cName == "main" {
		retC = "int"
	}

	if forwardOnly {
		g.w("%s %s(%s);", retC, cName, paramStr)
		return nil
	}

	// Full definition
	fmt.Fprintf(&g.sb, "%s %s(%s) {\n", retC, cName, paramStr)
	g.push()

	// New scope for the function body
	saved := g.scope
	g.scope = newScope(saved)
	for _, p := range fn.Params {
		g.scope.define(p.Name, p.Type)
	}

	if err := g.genBlock(fn.Body); err != nil {
		return err
	}

	// main() must return 0
	if fn.Name == "main" {
		g.w("return 0;")
	}

	g.scope = saved
	g.pop()
	g.w("}")
	return nil
}

// ── Statements ────────────────────────────────────────────────────────────────

func (g *Codegen) genBlock(block *BlockStmt) error {
	saved := g.scope
	g.scope = newScope(saved)
	for _, s := range block.Stmts {
		if err := g.genStmt(s); err != nil {
			return err
		}
	}
	g.scope = saved
	return nil
}

func (g *Codegen) genStmt(s Stmt) error {
	switch v := s.(type) {
	case *VarDeclStmt:
		return g.genVarDecl(v)
	case *ShortVarDeclStmt:
		return g.genShortVarDecl(v)
	case *AssignStmt:
		return g.genAssign(v)
	case *ReturnStmt:
		return g.genReturn(v)
	case *IfStmt:
		return g.genIf(v)
	case *ForStmt:
		return g.genFor(v)
	case *BreakStmt:
		g.w("break;")
	case *ContinueStmt:
		g.w("continue;")
	case *ExprStmt:
		ce, err := g.genExprStr(v.Expr)
		if err != nil {
			return err
		}
		g.w("%s;", ce)
	case *IncDecStmt:
		target, err := g.genExprStr(v.Target)
		if err != nil {
			return err
		}
		g.w("%s%s;", target, v.Op)
	case *BlockStmt:
		fmt.Fprintf(&g.sb, "%*s{\n", g.indent*2, "")
		g.push()
		if err := g.genBlock(v); err != nil {
			return err
		}
		g.pop()
		g.w("}")
	}
	return nil
}

func (g *Codegen) genVarDecl(v *VarDeclStmt) error {
	// Infer type from initializer if not given
	t := v.Type
	if t == TypeUnknown && v.Value != nil {
		var err error
		t, err = g.inferType(v.Value)
		if err != nil {
			return err
		}
	}
	if t == TypeUnknown {
		t = TypeInt // default
	}
	g.scope.define(v.Name, t)

	if v.Value != nil {
		val, err := g.genExprStr(v.Value)
		if err != nil {
			return err
		}
		g.w("%s %s = %s;", t.CName(), v.Name, val)
	} else {
		// zero value
		switch t {
		case TypeInt:
			g.w("%s %s = 0LL;", t.CName(), v.Name)
		case TypeString:
			g.w("%s %s = \"\";", t.CName(), v.Name)
		case TypeBool:
			g.w("%s %s = 0;", t.CName(), v.Name)
		}
	}
	return nil
}

func (g *Codegen) genShortVarDecl(v *ShortVarDeclStmt) error {
	for i, name := range v.Names {
		var val Expr
		if i < len(v.Values) {
			val = v.Values[i]
		}
		t := TypeInt
		if val != nil {
			var err error
			t, err = g.inferType(val)
			if err != nil {
				return err
			}
		}
		g.scope.define(name, t)
		if val != nil {
			valStr, err := g.genExprStr(val)
			if err != nil {
				return err
			}
			g.w("%s %s = %s;", t.CName(), name, valStr)
		} else {
			g.w("%s %s = 0;", t.CName(), name)
		}
	}
	return nil
}

func (g *Codegen) genAssign(v *AssignStmt) error {
	target, err := g.genExprStr(v.Target)
	if err != nil {
		return err
	}
	val, err := g.genExprStr(v.Value)
	if err != nil {
		return err
	}
	g.w("%s = %s;", target, val)
	return nil
}

func (g *Codegen) genReturn(v *ReturnStmt) error {
	if v.Value == nil {
		g.w("return;")
		return nil
	}
	val, err := g.genExprStr(v.Value)
	if err != nil {
		return err
	}
	g.w("return %s;", val)
	return nil
}

func (g *Codegen) genIf(v *IfStmt) error {
	cond, err := g.genExprStr(v.Cond)
	if err != nil {
		return err
	}
	fmt.Fprintf(&g.sb, "%*sif (%s) {\n", g.indent*2, "", cond)
	g.push()
	if err := g.genBlock(v.Then); err != nil {
		return err
	}
	g.pop()

	if v.Else != nil {
		fmt.Fprintf(&g.sb, "%*s} else ", g.indent*2, "")
		switch e := v.Else.(type) {
		case *IfStmt:
			// else if
			cond2, err := g.genExprStr(e.Cond)
			if err != nil {
				return err
			}
			fmt.Fprintf(&g.sb, "if (%s) {\n", cond2)
			g.push()
			if err := g.genBlock(e.Then); err != nil {
				return err
			}
			g.pop()
			// recurse for further else-if chains
			if e.Else != nil {
				tmp := &IfStmt{Cond: e.Cond, Then: e.Then, Else: e.Else}
				_ = tmp
				// close current and open else
				fmt.Fprintf(&g.sb, "%*s} else {\n", g.indent*2, "")
				g.push()
				if err := g.genStmt(e.Else); err != nil {
					return err
				}
				g.pop()
			}
			g.w("}")
		case *BlockStmt:
			fmt.Fprintf(&g.sb, "{\n")
			g.push()
			if err := g.genBlock(e); err != nil {
				return err
			}
			g.pop()
			g.w("}")
		}
	} else {
		g.w("}")
	}
	return nil
}

func (g *Codegen) genFor(v *ForStmt) error {
	var init, cond, post string

	if v.Init != nil {
		// generate init stmt inline (no newline)
		inner := &Codegen{funcs: g.funcs, scope: g.scope}
		inner.indent = 0
		if err := inner.genStmt(v.Init); err != nil {
			return err
		}
		s := strings.TrimSpace(inner.sb.String())
		s = strings.TrimSuffix(s, ";")
		init = s
	}
	if v.Cond != nil {
		var err error
		cond, err = g.genExprStr(v.Cond)
		if err != nil {
			return err
		}
	} else {
		cond = "1" // infinite
	}
	if v.Post != nil {
		inner := &Codegen{funcs: g.funcs, scope: g.scope}
		inner.indent = 0
		if err := inner.genStmt(v.Post); err != nil {
			return err
		}
		s := strings.TrimSpace(inner.sb.String())
		s = strings.TrimSuffix(s, ";")
		post = s
	}

	fmt.Fprintf(&g.sb, "%*sfor (%s; %s; %s) {\n", g.indent*2, "", init, cond, post)
	g.push()
	if err := g.genBlock(v.Body); err != nil {
		return err
	}
	g.pop()
	g.w("}")
	return nil
}

// ── Expressions ───────────────────────────────────────────────────────────────

func (g *Codegen) genExprStr(e Expr) (string, error) {
	switch v := e.(type) {
	case *IntLit:
		return fmt.Sprintf("%dLL", v.Value), nil

	case *StringLit:
		return fmt.Sprintf("%q", v.Value), nil

	case *BoolLit:
		if v.Value {
			return "1", nil
		}
		return "0", nil

	case *Identifier:
		return v.Name, nil

	case *UnaryExpr:
		operand, err := g.genExprStr(v.Operand)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("(%s%s)", v.Op, operand), nil

	case *BinaryExpr:
		left, err := g.genExprStr(v.Left)
		if err != nil {
			return "", err
		}
		right, err := g.genExprStr(v.Right)
		if err != nil {
			return "", err
		}
		// String concatenation: use runtime helper
		if v.Op == "+" {
			lt, _ := g.inferType(v.Left)
			if lt == TypeString {
				tmp := g.tmpVar()
				g.w("char* %s; { int _l = strlen(%s)+strlen(%s)+1; %s = (char*)malloc(_l); strcpy(%s,%s); strcat(%s,%s); }",
					tmp, left, right, tmp, tmp, left, tmp, right)
				return tmp, nil
			}
		}
		return fmt.Sprintf("(%s %s %s)", left, v.Op, right), nil

	case *SelectorExpr:
		return fmt.Sprintf("%s.%s", v.Object.(*Identifier).Name, v.Field), nil

	case *CallExpr:
		return g.genCall(v)

	default:
		return "", fmt.Errorf("unknown expression type %T", e)
	}
}

// ── Built-in / stdlib calls ───────────────────────────────────────────────────

func (g *Codegen) genCall(c *CallExpr) (string, error) {
	// fmt.Println / fmt.Print / fmt.Printf
	if sel, ok := c.Func.(*SelectorExpr); ok {
		if id, ok2 := sel.Object.(*Identifier); ok2 && id.Name == "fmt" {
			return g.genFmtCall(sel.Field, c.Args)
		}
	}

	// User-defined function call
	if id, ok := c.Func.(*Identifier); ok {
		fn, known := g.funcs[id.Name]
		var argStrs []string
		for _, a := range c.Args {
			s, err := g.genExprStr(a)
			if err != nil {
				return "", err
			}
			argStrs = append(argStrs, s)
		}
		_ = fn
		_ = known
		return fmt.Sprintf("%s(%s)", id.Name, strings.Join(argStrs, ", ")), nil
	}

	return "", fmt.Errorf("unsupported call expression %T", c.Func)
}

func (g *Codegen) genFmtCall(fn string, args []Expr) (string, error) {
	switch fn {
	case "Println":
		if len(args) == 0 {
			return `printf("\n")`, nil
		}
		var parts []string
		for _, a := range args {
			t, _ := g.inferType(a)
			s, err := g.genExprStr(a)
			if err != nil {
				return "", err
			}
			switch t {
			case TypeInt:
				parts = append(parts, fmt.Sprintf("_print_int(%s)", s))
			case TypeBool:
				parts = append(parts, fmt.Sprintf("_print_bool(%s)", s))
			default:
				parts = append(parts, fmt.Sprintf("_print_str(%s)", s))
			}
		}
		// add spaces between args, newline at end
		if len(parts) == 1 {
			// replace _print with _println for single arg
			out := strings.Replace(parts[0], "_print_", "_println_", 1)
			return out, nil
		}
		var calls []string
		for i, p := range parts {
			calls = append(calls, p)
			if i < len(parts)-1 {
				calls = append(calls, `_print_str(" ")`)
			}
		}
		calls = append(calls, `printf("\n")`)
		return strings.Join(calls, ", "), nil

	case "Print":
		var parts []string
		for _, a := range args {
			t, _ := g.inferType(a)
			s, err := g.genExprStr(a)
			if err != nil {
				return "", err
			}
			switch t {
			case TypeInt:
				parts = append(parts, fmt.Sprintf("_print_int(%s)", s))
			case TypeBool:
				parts = append(parts, fmt.Sprintf("_print_bool(%s)", s))
			default:
				parts = append(parts, fmt.Sprintf("_print_str(%s)", s))
			}
		}
		return strings.Join(parts, ", "), nil

	case "Printf":
		if len(args) == 0 {
			return "", fmt.Errorf("fmt.Printf needs at least one argument")
		}
		fmtStr, err := g.genExprStr(args[0])
		if err != nil {
			return "", err
		}
		var rest []string
		for _, a := range args[1:] {
			s, err := g.genExprStr(a)
			if err != nil {
				return "", err
			}
			rest = append(rest, s)
		}
		if len(rest) > 0 {
			return fmt.Sprintf("printf(%s, %s)", fmtStr, strings.Join(rest, ", ")), nil
		}
		return fmt.Sprintf("printf(%s)", fmtStr), nil

	case "Sprintf":
		// Very limited: just pass through to snprintf using a temp buffer
		if len(args) == 0 {
			return `""`, nil
		}
		fmtStr, err := g.genExprStr(args[0])
		if err != nil {
			return "", err
		}
		var rest []string
		for _, a := range args[1:] {
			s, err := g.genExprStr(a)
			if err != nil {
				return "", err
			}
			rest = append(rest, s)
		}
		tmp := g.tmpVar()
		if len(rest) > 0 {
			g.w("char %s[1024]; snprintf(%s, sizeof(%s), %s, %s);",
				tmp, tmp, tmp, fmtStr, strings.Join(rest, ", "))
		} else {
			g.w("char %s[1024]; snprintf(%s, sizeof(%s), %s);", tmp, tmp, tmp, fmtStr)
		}
		return tmp, nil
	}

	return "", fmt.Errorf("unsupported fmt.%s", fn)
}

// ── Type inference ────────────────────────────────────────────────────────────

func (g *Codegen) inferType(e Expr) (GoType, error) {
	switch v := e.(type) {
	case *IntLit:
		return TypeInt, nil
	case *StringLit:
		return TypeString, nil
	case *BoolLit:
		return TypeBool, nil
	case *Identifier:
		sym := g.scope.lookup(v.Name)
		if sym != nil {
			return sym.Type, nil
		}
		// Check if it's a known function
		if fn, ok := g.funcs[v.Name]; ok {
			return fn.ReturnType, nil
		}
		return TypeUnknown, nil
	case *BinaryExpr:
		lt, err := g.inferType(v.Left)
		if err != nil {
			return TypeUnknown, err
		}
		switch v.Op {
		case "==", "!=", "<", ">", "<=", ">=", "&&", "||":
			return TypeBool, nil
		default:
			return lt, nil
		}
	case *UnaryExpr:
		if v.Op == "!" {
			return TypeBool, nil
		}
		return g.inferType(v.Operand)
	case *CallExpr:
		if sel, ok := v.Func.(*SelectorExpr); ok {
			if id, ok2 := sel.Object.(*Identifier); ok2 && id.Name == "fmt" {
				if sel.Field == "Sprintf" {
					return TypeString, nil
				}
				return TypeVoid, nil
			}
		}
		if id, ok := v.Func.(*Identifier); ok {
			if fn, ok := g.funcs[id.Name]; ok {
				return fn.ReturnType, nil
			}
		}
		return TypeUnknown, nil
	}
	return TypeUnknown, nil
}
